#!/usr/bin/env python3
"""The SECOND review packet: only what widening the watched population adds (transition.py
--packet-widening). Deterministic, like everything transition.py renders.

The first packet (REVIEW_PACKET_2026-10-13.md) covers the narrow population the gate watched until
v0.4: `MachLib.*` theorems that pass extract_statement.lean's substring filter. The widened
population is every theorem MachLib declares -- its own modules or the `MachLib`/`Certcom`
namespaces, private ones decided by identity -- minus tools/theorem_ledger's exclusion rule, so the
gate watches exactly what the theorem ledger counts. This packet lists, for a reviewer:
  W1 the rule and what it excludes, with counts;
  W2 the theorems the widening ADDS, by origin and policy tier, every non-approved one in full;
  W3 the theorems it DROPS (watched before, excluded by the rule now);
  W4 how the added theorems moved since 2026-09-03;
  W5-W6 the 16 axioms restated under their names and the 13 added, which only unwatched theorems used.
"""
from __future__ import annotations

import collections
import json

import transition as T
import transition_render as R
import transition_report_text as RT

RULES = {
    "internal-name": "an internal detail name (`_`-prefixed or numeric component, `match_N`, `proof_N`, `eq_N`): "
                     "auxiliary proofs, macro rules, hygienic names",
    "recursor": "a recursor (`T.rec`)",
    "aux-recursor": "casesOn / recOn / brecOn / binductionOn / below",
    "no-confusion": "a noConfusion construction",
    "matcher": "a compiled pattern match",
    "reserved-name": "a name Lean generates on demand: equation lemmas (`eq_def`, `eq_unfold`), congruence "
                     "lemmas (`congr_simp`), functional induction",
    "constructor-lemma": "`C.inj`, `C.injEq`, `C.sizeOf_spec` for a constructor `C`",
    "child-of-auxiliary": "its parent is itself excluded (`T.below.c`)",
    "no-source-range": "no source range: generated, not elaborated from text",
}


def origin(name: str, private: set) -> str:
    if name in private:
        return "private"
    if name.startswith("Certcom."):
        return "Certcom.*"
    if name.startswith("MachLib."):
        return "MachLib.* (dropped by the old name filter)"
    return "outside the MachLib/Certcom namespaces"


def packet(t: dict, manifest: dict, ev: dict) -> str:
    d = RT._derived(t, ev)
    so, sn = R._stmts(ev)
    hist = R._history(ev)
    narrow = set(t.get("narrow_population") or [])
    _, all_new = T.load_sigset(ev["sigs_new"])
    _, all_old = T.load_sigset(ev["sigs_old"])
    new_w, old_w = T.watched(all_new), T.watched(all_old)
    pop = json.loads(ev["population"].read_text()) if "population" in ev else {}
    priv_new = set((pop.get("new") or {}).get("private", []))
    priv_old = set((pop.get("old") or {}).get("private", []))
    p_new = d["p_new"]
    added = sorted(k for k in new_w if k not in narrow)
    dropped = sorted(k for k in narrow if k not in new_w)
    rows = {r["theorem"]: r for r in t["rows"]}
    L = []
    w = L.append
    w("# MachSig trust gate — second review packet: what widening the watched population adds")
    w("")
    w(f"Generated by `tools/machsig/transition.py --packet-widening`; deterministic. Companion to "
      f"`{(t.get('names') or {}).get('md', '?')}` (the widened transition) and to the first packet, "
      "`REVIEW_PACKET_2026-10-13.md` (the narrow population, already reviewed). This packet covers ONLY what the "
      "widening adds. The owner picks between the narrow candidate and the widened one; nothing here is accepted.")
    w("")
    w(f"**Summary.** Watched now: narrow {len(narrow)}, widened {len(new_w)}. The widening adds **{len(added)}** "
      f"theorems and drops **{len(dropped)}**. Widened at 23e0d047: {len(old_w)} (the 2026-09-03 baseline watched "
      f"{t['population']['baseline_0903']}).")
    w("")
    w("## W1. The rule")
    w("")
    w("A theorem is watched when its module is `MachLib`, `MachLib.*` or `CertcomLibm`, or its name is under "
      "`MachLib` or `Certcom`, and tools/theorem_ledger's exclusion rule does not exclude it. Private theorems "
      "(`_private.<module>.0.<name>`) are decided by `isPrivateName` and judged by their user name, never by "
      "spelling. The rule is the theorem ledger's, copied into extract_trust.lean and extract_statement.lean, so "
      f"the gate watches exactly what MachLib counts as its theorems (the ledger's published total is 9,431).")
    w("")
    w("| exclusion reason | what it is | theorems excluded at 23e0d047 | now |")
    w("|---|---|---:|---:|")
    eo = (pop.get("old") or {}).get("excluded_by_reason", {})
    en = (pop.get("new") or {}).get("excluded_by_reason", {})
    for reason in sorted(set(eo) | set(en)):
        w(f"| `{reason}` | {RULES.get(reason, '?')} | {eo.get(reason, 0)} | {en.get(reason, 0)} |")
    w(f"| **counted (watched)** | | **{(pop.get('old') or {}).get('counted', '?')}** | "
      f"**{(pop.get('new') or {}).get('counted', '?')}** |")
    w("")
    w("Why exclude these at all: each is generated by Lean from a declaration MachLib does make (a definition's "
      "equation lemmas, a constructor's injectivity lemma, an auxiliary proof inside a theorem). Their axioms "
      "already reach the gate through the declarations they serve, and their statements are fixed by those "
      "declarations, which the definition-closure digest now covers.")
    w("")
    w(f"## W2. Theorems the widening adds ({len(added)})")
    w("")
    by = collections.Counter((origin(k, priv_new), T.tier(new_w[k]["axioms"], p_new)[0]) for k in added)
    w("| origin | approved_policy | conditional | unchecked | total |")
    w("|---|---:|---:|---:|---:|")
    for o in sorted({o for o, _ in by}):
        a, c, u = by.get((o, "approved_policy"), 0), by.get((o, "conditional"), 0), by.get((o, "unchecked"), 0)
        w(f"| {o} | {a} | {c} | {u} | {a + c + u} |")
    w("")
    nonapp = [k for k in added if T.tier(new_w[k]["axioms"], p_new)[0] != "approved_policy"]
    w(f"Every added theorem outside the approved policy ({len(nonapp)}), with what it is conditional on:")
    w("")
    w("| theorem | origin | tier | outside the policy |")
    w("|---|---|---|---|")
    for k in nonapp:
        tr, out = T.tier(new_w[k]["axioms"], p_new)
        w(f"| `{k}` | {origin(k, priv_new)} | {tr} | {', '.join('`' + a + '`' for a in out)} |")
    w("")
    ax_use = collections.Counter(a for k in added for a in new_w[k]["axioms"]
                                 if T.axiom_class(a, p_new) not in ("std",))
    only = sorted(a for a in ax_use if not any(a in new_w[k]["axioms"] for k in narrow if k in new_w))
    w(f"Axioms that ONLY added theorems use ({len(only)}) — invisible to the narrow gate whatever happens to them:")
    w("")
    w(", ".join(f"`{a}` ({ax_use[a]})" for a in only) or "none")
    w("")
    w(f"## W3. Theorems the widening drops ({len(dropped)})")
    w("")
    w("Watched by the narrow population, excluded by the rule. If the owner picks the widened candidate, these "
      "leave the watched set in that rebaseline (the gate itself would otherwise FAIL them as `removed`).")
    w("")
    w("| theorem | exclusion reason now |")
    w("|---|---|")
    auxn = (pop.get("new") or {}).get("aux", {})
    for k in dropped:
        w(f"| `{k}` | `{auxn.get(k, '?')}` |")
    w("")
    w("## W4. How the added theorems moved since 2026-09-03")
    w("")
    w("The old side is the widened extraction at 23e0d047 (no historical baseline watched them).")
    w("")
    kinds = collections.Counter((rows[k]["kind"], rows[k].get("trust_class")) for k in added if k in rows)
    unchanged = sum(1 for k in added if k not in rows)
    w("| kind | trust class | count |")
    w("|---|---|---:|")
    for (kd, cl), n in sorted(kinds.items()):
        w(f"| {kd} | {cl} | {n} |")
    w(f"| unchanged | | {unchanged} |")
    w("")
    ne = sorted(k for k in added if k in rows and rows[k].get("explained_by_discharge") is False)
    w(f"Changed but NOT explained by a discharged axiom ({len(ne)}), in full:")
    w("")
    fh = R._file_history(ev)
    for k in ne:
        L += RT._full_entry(rows[k], so, sn, d["p_old"], p_new, t["moved_axioms"], fh)
    promoted_here = collections.Counter(a for k in added if k in rows for a in rows[k]["entered"]
                                        if T.axiom_class(a, p_new) == "trusted"
                                        and T.axiom_class(a, d["p_old"]) != "trusted")
    if promoted_here:
        w("Promoted axioms (E1/E2) entering added theorems: "
          + ", ".join(f"`{a}` {n}" for a, n in sorted(promoted_here.items())))
        w("")
    L += [ln.replace("## G.", "## W5a.").replace("## H.", "## W5.").replace("## I.", "## W6.")
            .replace("## J.", "## W7.")
          for ln in RT.axiom_and_definition_sections(t, d, so, sn, hist, dependents_label="watched (widened)")]
    w("## Sign-off")
    w("")
    w("| section | reviewer | verdict | date |")
    w("|---|---|---|---|")
    for s in ("W1. The rule", "W2. Added theorems", "W3. Dropped theorems", "W4. Movement of added theorems",
              "W5. Restated axioms", "W5a. Redefinitions (widened)", "W6. Added axioms", "W7. Promotions"):
        w(f"| {s} | | | |")
    w("")
    w("Evidence:")
    w("")
    L += RT._evidence_table(manifest)
    return "\n".join(L) + "\n"
