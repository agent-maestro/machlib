def _stmt_block(label: str, st: dict | None) -> list[str]:
    return [f"{label}:", "", "```lean", (st or {}).get("type", "(unavailable)"), "```", ""]


def axiom_and_definition_sections(t: dict, d: dict, so: dict, sn: dict, hist: dict,
                                  dependents_label: str = "watched") -> list[str]:
    L = []
    w = L.append
    am = t["axiom_moves"]
    redef = d["redef"]
    if redef is not None:
        w(f"## G. Definitions changed under unchanged statements (E3): "
          f"{sum(1 for c in redef['changed'] if c['old_kind'] and c['new_kind'])} changed in place, "
          f"{d['n_redefined']} {dependents_label} theorems reach one")
        w("")
        w("StatementDigest hashes a theorem's stored type, so a changed DEFINITION under it was invisible until "
          "v0.4. These are the constants whose own type or body changed between the revisions (or that changed "
          "kind, e.g. an axiom that became a definition), with the number of theorems whose statement reaches "
          "each through definition bodies. Every such theorem is in the JSON (`redefined: true`) and in "
          "`redefinition.json` with the definitions it reaches.")
        w("")
        both = [c for c in redef["changed"] if c["old_kind"] and c["new_kind"]]
        oneside = [c for c in redef["changed"] if not (c["old_kind"] and c["new_kind"]) and d["by_def"].get(c["name"])]
        w(f"{len(both)} constants exist at both revisions with a different type, body or kind; "
          f"{len(redef['changed']) - len(both)} exist on one side only, of which {len(oneside)} are reached by a "
          "redefined theorem (a changed body can start using a new constant):")
        w("")
        w("| constant | 2026-09-03 | now | theorems reaching it |")
        w("|---|---|---|---:|")
        for c in sorted(both, key=lambda c: (-d["by_def"].get(c["name"], 0), c["name"])) + \
                sorted(oneside, key=lambda c: (-d["by_def"].get(c["name"], 0), c["name"])):
            w(f"| `{c['name']}` | {c['old_kind'] or 'absent'} | {c['new_kind'] or 'absent'} | {d['by_def'].get(c['name'], 0)} |")
        w("")
        clamp = sorted(th for th, cs in redef["theorem_reaches"].items() if "MachLib.Real.clamp" in cs)
        if clamp:
            w(f"The `clamp` change (9802f19e: `min (max x lo) hi` became `max lo (min x hi)`; they differ only when "
              f"lo > hi) reaches {len(clamp)} theorems. Each now describes the language's clamp; for an inverted "
              "band it says something different from what it said on 2026-09-03:")
            w("")
            w("| theorem | statement |")
            w("|---|---|")
            for th in clamp:
                st = (sn.get(th) or so.get(th) or {}).get("type")
                w(f"| `{th}` | {R._cut(st, C2_CUT).replace('|', chr(92) + '|')} |")
            w("")
    rest = am["restated"]
    w(f"## H. Axioms restated under the same name ({len(rest)})")
    w("")
    w("The baseline pinned axiom NAMES until v0.4; a footprint holding one of these looked unchanged. "
      f"{dependents_label.capitalize()} theorems resting on each, before and now:")
    w("")
    for a in rest:
        w(f"#### `{a}`")
        w("")
        cs = R._commits([a], hist, 4)
        w(f"* {dependents_label} dependents: {am['watched_dependents_old'].get(a, 0)} at 23e0d047, "
          f"{am['watched_dependents_new'].get(a, 0)} now; class now {T.axiom_class(a, d['p_new'])}")
        w("")
        L += _stmt_block("Old statement", so.get(a))
        L += _stmt_block("New statement", sn.get(a))
    born = t["moved_axioms"]["axiom_now_not_then"]
    w(f"## I. Axioms added since 2026-09-03 ({len(born)})")
    w("")
    for a in born:
        cs = R._commits([a], hist, 3)
        w(f"#### `{a}`")
        w("")
        w(f"* class now {T.axiom_class(a, d['p_new'])}; {dependents_label} dependents now "
          f"{am['watched_dependents_new'].get(a, 0)}; introduced in: " + ("; ".join(cs) or "—"))
        w("")
        L += _stmt_block("Statement", sn.get(a))
    pd = t["policy_delta"]
    w(f"## J. Axioms promoted into trustedFootprint (E1, E2): {len(pd['trusted_added'])}")
    w("")
    w("A promotion raises trust without any proof changing. The gate (v0.4) pins the policy and FAILS "
      "`policy-widened` on any addition until a reviewed rebaseline. Entries into existing footprints:")
    w("")
    w("| axiom | 2026-09-03 class | entered N existing footprints | introduced as an axiom |")
    w("|---|---|---:|---|")
    for a in pd["trusted_added"]:
        new_ax = a in born
        w(f"| `{a}` | {T.axiom_class(a, d['p_old'])} | {d['promoted_in'].get(a, 0)} | "
          f"{'since 2026-09-03' if new_ax else 'before 2026-09-03'} |")
    w("")
    return L


