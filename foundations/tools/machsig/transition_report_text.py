#!/usr/bin/env python3
"""The prose of the transition report and the review packet (transition.py renders through this).

Every number printed here is computed from transition.build()'s output or an evidence file in the
same call; nothing is typed in. Sorted everywhere, no clock: same evidence, same bytes.
"""
from __future__ import annotations

import collections
import json

import transition as T
import transition_render as R

C2_CUT = 160


def _mod_file(mod: str | None) -> str:
    return (mod or "?").replace(".", "/") + ".lean"


def _where(st: dict | None, fallback_mod: str | None) -> str:
    if st and not st.get("missing"):
        return f"`{_mod_file(st.get('module'))}:{st.get('line')}`"
    return f"`{_mod_file(fallback_mod)}`"


def _tier(side: dict | None) -> str:
    if side is None:
        return "—"
    t = side.get("tier") or "?"
    return t if t != "conditional" else f"conditional on {len(side.get('outside_policy') or [])}"


def _evidence_table(manifest: dict) -> list[str]:
    out = ["| evidence file | sha256 |", "|---|---|"]
    out += [f"| `{k}` | `{v}` |" for k, v in sorted(manifest.items())]
    return out


def _derived(t: dict, ev: dict) -> dict:
    c = R.counts(t)
    rows = t["rows"]
    changed_sets = [r for r in rows if r["kind"] in ("grew", "shrank", "swap", "restated")]
    mech = collections.Counter(r.get("mechanism") for r in changed_sets)
    expl = sum(1 for r in changed_sets if r.get("explained_by_discharge"))
    not_expl = [r for r in changed_sets if r.get("explained_by_discharge") is False]
    tiers = collections.Counter((r["old"].get("tier") if r["old"] else None, r["new"]["tier"] if r["new"] else None)
                                for r in rows)
    p_old, p_new = R._policies(ev)
    cond_in = collections.Counter(a for r in rows for a in r["entered"] if T.axiom_class(a, p_new) == "conditional")
    cond_out = collections.Counter(a for r in rows for a in r["left"] if T.axiom_class(a, p_old) == "conditional")
    std_moves = sum(1 for r in rows if any(a in T.STD for a in r["entered"] + r["left"]))
    left_by_ax = collections.Counter(a for r in rows for a in r["left"])
    entered_new_ax = sum(1 for r in rows if set(r["entered"]) & set(t["moved_axioms"]["axiom_now_not_then"]))
    promoted_in = collections.Counter(a for r in rows for a in r["entered"]
                                      if T.axiom_class(a, p_new) == "trusted" and T.axiom_class(a, p_old) != "trusted")
    redef = R._redefinition(ev)
    by_def = collections.Counter(c for v in (redef or {}).get("theorem_reaches", {}).values() for c in v)
    return {"c": c, "changed_sets": changed_sets, "mech": mech, "explained": expl, "not_explained": not_expl,
            "tiers": tiers, "cond_in": cond_in, "cond_out": cond_out, "std_moves": std_moves,
            "left_by_ax": left_by_ax, "entered_new_ax": entered_new_ax, "p_old": p_old, "p_new": p_new,
            "promoted_in": promoted_in, "redef": redef, "by_def": by_def,
            "n_redefined": sum(1 for r in rows if r.get("redefined"))}


