def _full_entry(r: dict, so: dict, sn: dict, p_old: dict, p_new: dict, moved: dict,
                fhist: dict | None = None) -> list[str]:
    L = []
    w = L.append
    th = r["theorem"]
    o, n = r["old"], r["new"]
    w(f"#### `{th}`")
    w("")
    w(f"* kind **{r['kind']}**, trust class `{r.get('trust_class')}`, mechanism `{r.get('mechanism', '—')}`; "
      f"cause: {', '.join(r['causes']) or '—'}")
    w(f"* where: old {_where(so.get(th), r.get('module')) if o else '—'}, new {_where(sn.get(th), r.get('module')) if n else '—'}")
    w(f"* footprint: {o['ax'] if o else '—'} → {n['ax'] if n else '—'} axioms; tier {_tier(o)} → {_tier(n)}")
    if r.get("statement_now_held_by") is not None:
        held = r["statement_now_held_by"]
        w(f"* the identical statement is now held by: {', '.join('`'+x+'`' for x in held) if held else 'no watched theorem'}"
          f"; `{th}` itself is {'still' if r.get('still_in_new_environment') else 'NOT'} in the new environment")
    if r["entered"]:
        w(f"* entered: " + ", ".join(R._ax_label(a, "new", p_old, p_new, moved) for a in r["entered"]))
    if r["left"]:
        w(f"* left: " + ", ".join(R._ax_label(a, "old", p_old, p_new, moved) for a in r["left"]))
    f = _mod_file(r.get("module"))
    if fhist is not None and f in fhist:
        cs = fhist[f]
        w(f"* commits touching `{f}` between the revisions ({len(cs)}): " +
          ("; ".join(f"`{c['commit'][:10]}` {c['date']} {c['subject']}" for c in cs[:5]) or "none") +
          (f"; … {len(cs) - 5} more" if len(cs) > 5 else ""))
    w("")
    if o is not None:
        w("Old statement:")
        w("")
        w("```lean")
        w((so.get(th) or {}).get("type", "(unavailable)"))
        w("```")
    if n is not None and (o is None or o["d"] != n["d"]):
        w("New statement:")
        w("")
        w("```lean")
        w((sn.get(th) or {}).get("type", "(unavailable)"))
        w("```")
    elif n is not None:
        w("(statement unchanged: identical digest)")
    w("")
    if o is not None and o.get("axioms") is not None:
        w(f"Old axioms ({len(o['axioms'])}): " + ", ".join(f"`{a}`" for a in o["axioms"]))
        w("")
    if n is not None:
        w(f"New axioms ({len(n['axioms'])}): " + ", ".join(f"`{a}`" for a in n["axioms"]))
        w("")
    return L


def packet(t: dict, manifest: dict, ev: dict) -> str:
    d = _derived(t, ev)
    so, sn = R._stmts(ev)
    hist = R._history(ev)
    fh = R._file_history(ev)
    moved = t["moved_axioms"]
    p_old, p_new = d["p_old"], d["p_new"]
    rows = t["rows"]
    removed = [r for r in rows if r["kind"] == "removed"]
    restated = [r for r in rows if r["kind"] == "restated"]
    assumption = [r for r in rows if r["kind"] in ("grew", "shrank", "swap")
                  and r.get("trust_class") not in ("standard-only", "no-axiom-change")]
    other_cls = [r for r in rows if r.get("trust_class") in ("sorry", "other")]
    L = []
    w = L.append
    w("# MachSig trust gate — review packet (step 5 of the ruling of 2026-10-13)")
    w("")
    w(f"Generated by `tools/machsig/transition.py`; deterministic. Companion to `TRANSITION_2026-10-13.md`. "
      f"**{len(removed)} removals, {len(restated)} restatements, {len(assumption)} changes affecting proof "
      f"assumptions** (every grew/shrank/swap whose axiom delta is not standard-Lean-only), "
      f"{len(other_cls)} involving sorryAx, compiler trust or an undeclared axiom.")
    w("")
    w("## For a reviewer who has never seen MachLib")
    w("")
    w("MachLib is a Lean 4 library with **no Mathlib**: the real numbers are themselves axiomatised "
      "(`MachLib.Real : Type`, `addR`, `mul_comm`, `exp`, `exp_add`, … are `axiom` declarations). So almost "
      "every theorem rests on dozens of MachLib axioms, and a theorem's *footprint* — what `#print axioms` "
      "lists — is its whole trusted base. Lean's own three standard axioms are `propext`, `Classical.choice`, "
      "`Quot.sound`.")
    w("")
    w("`foundations/AxiomLedger.lean` declares the policy. `knownAxioms` is every live axiom; "
      "`trustedFootprint` is the approved foundation. The theorem ledger (`tools/theorem_ledger/ledger.py`) "
      "puts each theorem in one tier: **approved_policy** (footprint inside `trustedFootprint`), "
      "**conditional** (uses a declared axiom outside it; the record names which), **unchecked** "
      "(sorryAx, compiler trust, or an undeclared axiom).")
    w("")
    w("The gate (`tools/machsig/trust_gate.py`) is a ratchet: for a theorem whose statement did not change, "
      "no axiom may enter its footprint without a reviewed rebaseline. Between 2026-09-03 and 2026-10-13 it "
      "compared stale signatures and saw nothing. This packet lists what it missed that a person must judge.")
    w("")
    w("**Why so many footprints GREW without anything getting less trustworthy.** On 2026-10-04 three commits "
      f"turned {len(moved['axiom_then_not_now'])} axioms into theorems or definitions (`exp_pos`, `natCast`, "
      "`mul_lt_mul_of_pos_right`, …). A theorem that used `exp_pos` as an axiom now uses its *proof*, which "
      "rests on more basic axioms (`exp_add`, `exp_surj`, field axioms). So `exp_pos` leaves the footprint and "
      "those enter: the count grows, while the set of things assumed shrinks to the foundation. The report "
      "checks this mechanically for each change (section 4 there); section C1 below is what it does not explain.")
    w("")
    w("**What to decide**, per item: is the change intended and acceptable? Concretely: (A) a removed theorem "
      "was meant to go, or moved; (B) a restated theorem's new statement is the intended one; (C) an axiom "
      "entering a footprint is one the theorem should rest on, and a conditional axiom leaving is a real "
      "discharge. Mark rejections; the baseline is committed only after every section is signed off.")
    w("")
    w("**Check any line yourself** (from `foundations/` of a built tree at either revision):")
    w("")
    w("```")
    w("printf 'import MachLib\\n#print axioms MachLib.Real.exp_nonneg\\n' > /tmp/p.lean && lake env lean /tmp/p.lean")
    w("git log --oneline 23e0d047..c3046961 -- foundations/MachLib/<File>.lean")
    w("```")
    w("")
    w("Full per-theorem axiom sets for every section: `transition_2026-10-13.json` (`rows[].old.axiom_set`, "
      "`rows[].new.axiom_set` → `axiom_sets`). Sections A, B and C1 print them inline.")
    w("")
    w(f"## A. Removals ({len(removed)})")
    w("")
    for r in removed:
        L += _full_entry(r, so, sn, p_old, p_new, moved, fh)
    w(f"## B. Restatements ({len(restated)})")
    w("")
    for r in restated:
        L += _full_entry(r, so, sn, p_old, p_new, moved, fh)
    w(f"## C. Changes affecting proof assumptions ({len(assumption)})")
    w("")
    cls = collections.Counter((r["kind"], r["trust_class"]) for r in assumption)
    w("| kind | class | count |")
    w("|---|---|---:|")
    for (kd, cl), n in sorted(cls.items()):
        w(f"| {kd} | {cl} | {n} |")
    w("")
    ne = [r for r in assumption if r.get("explained_by_discharge") is False]
    w(f"### C1. Not explained by a discharged axiom ({len(ne)}) — read each")
    w("")
    w("Either a still-live axiom left (the proof changed), or an axiom entered that no discharged axiom's proof "
      "accounts for. Shrinks here reduce trust and are low-risk; growths are the ones to read.")
    w("")
    for r in sorted(ne, key=lambda r: ({"grew": 0, "swap": 1, "shrank": 2}.get(r["kind"], 3), r["theorem"])):
        L += _full_entry(r, so, sn, p_old, p_new, moved, fh)
        if r.get("unexplained_entered"):
            w("Entered without a discharge to account for it: " +
              ", ".join(f"`{a}`" for a in r["unexplained_entered"]))
            w("")
    ex = [r for r in assumption if r.get("explained_by_discharge")]
    w(f"### C2. Explained by a discharged axiom ({len(ex)}), by delta group")
    w("")
    w("Within a group every theorem has the same entered and left axioms. Old set = new set − entered + left.")
    w("")
    by_g = collections.defaultdict(list)
    for r in ex:
        by_g[r.get("group")].append(r)
    gmeta = {g["id"]: g for g in t["groups"]}
    for gid in sorted(by_g, key=lambda x: (-len(by_g[x]), x)):
        g = gmeta[gid]
        rs = sorted(by_g[gid], key=lambda r: r["theorem"])
        disc = [a for a in g["left"] if a in moved["axiom_then_not_now"]]
        w(f"#### {gid} — {len(rs)} theorem(s), `{g['trust_class']}`")
        w("")
        w("* entered: " + (", ".join(R._ax_label(a, "new", p_old, p_new, moved) for a in g["entered"]) or "—"))
        w("* left: " + (", ".join(R._ax_label(a, "old", p_old, p_new, moved) for a in g["left"]) or "—"))
        cs = R._commits(disc, hist, 4)
        if cs:
            w("* discharged in: " + "; ".join(cs))
        w("")
        w("| theorem | where | AX | tier | statement |")
        w("|---|---|---|---|---|")
        for r in rs:
            st = sn.get(r["theorem"]) or so.get(r["theorem"])
            stmt = R._cut((st or {}).get("type"), C2_CUT).replace("|", "\\|")
            w(f"| `{r['theorem']}` | {_where(sn.get(r['theorem']), r.get('module'))} | {r['old']['ax']}→{r['new']['ax']} "
              f"| {_tier(r['old'])}→{_tier(r['new'])} | {stmt} |")
        w("")
    w(f"## D. sorryAx, compiler trust, undeclared axioms ({len(other_cls)} changes)")
    w("")
    w(f"No change involves them. sorryAx is in exactly {len(t['sorry_now'])} watched footprint(s): "
      + ", ".join(f"`{s}`" for s in t["sorry_now"])
      + f"; `tools/sorry_audit.lean` allowlists {', '.join('`'+s+'`' for s in t['sorry_allowlist'])}.")
    w("")
    newc = [r for r in rows if r["kind"] == "new" and r["new"]["tier"] != "approved_policy"]
    w(f"## E. New theorems outside the approved policy ({len(newc)} of {sum(1 for r in rows if r['kind'] == 'new')} new)")
    w("")
    w("Not changes to an existing assumption, listed so nothing conditional arrives unseen.")
    w("")
    w("| theorem | where | tier | conditional on |")
    w("|---|---|---|---|")
    for r in sorted(newc, key=lambda r: r["theorem"]):
        w(f"| `{r['theorem']}` | {_where(sn.get(r['theorem']), r.get('module'))} | {r['new']['tier']} | "
          f"{', '.join('`'+a+'`' for a in r['new']['outside_policy'])} |")
    w("")
    w(f"## F. The {len(t['baseline_edits'])} entries c3046961 accepted by hand")
    w("")
    w("Accepted against the stale signature set, so never reviewed against a live one. Each also appears above "
      "under its kind.")
    w("")
    w("| theorem | 2026-09-03 | c3046961 baseline | extracted now | equal |")
    w("|---|---|---|---|---|")
    for e in t["baseline_edits"]:
        f = lambda x: f"AX{x['ax']}" if x else "—"  # noqa: E731
        w(f"| `{e['theorem']}` | {f(e['baseline_0903'])} | {f(e['baseline_c3046961'])} | {f(e['extracted_new'])} "
          f"| {'yes' if e['matches_extraction'] else 'NO'} |")
    w("")
    L += axiom_and_definition_sections(t, d, so, sn, hist)
    w("## Sign-off")
    w("")
    w("| section | reviewer | verdict | date |")
    w("|---|---|---|---|")
    for s in ("A. Removals", "B. Restatements", "C1. Not explained by discharge", "C2. Explained by discharge",
              "D. sorry / other", "E. New conditional theorems", "F. c3046961 hand edits",
              "G. Definitions changed under unchanged statements (E3)", "H. Axioms restated under the same name",
              "I. Axioms added since 2026-09-03", "J. Axioms promoted into trustedFootprint (E1, E2)"):
        w(f"| {s} | | | |")
    w("")
    w("Evidence:")
    w("")
    L += _evidence_table(manifest)
    return "\n".join(L) + "\n"
